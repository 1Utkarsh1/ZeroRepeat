const std = @import("std");
const core = @import("zerorepeat");
const options = @import("test_paths");

test "the same native network fixture connects on the host and is denied inside OS isolation" {
    const a = std.testing.allocator;
    const io = std.testing.io;
    if (@import("builtin").os.tag == .linux) std.Io.Dir.cwd().access(io, "/usr/bin/bwrap", .{ .execute = true }) catch return error.SkipZigTest;
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    try tmp.dir.createDir(io, "workspace", .default_dir);
    try tmp.dir.createDir(io, "scratch", .default_dir);
    var bytes: [std.Io.Dir.max_path_bytes]u8 = undefined;
    const len = try tmp.dir.realPath(io, &bytes);
    const workspace = try std.fmt.allocPrint(a, "{s}/workspace", .{bytes[0..len]});
    defer a.free(workspace);
    const scratch = try std.fmt.allocPrint(a, "{s}/scratch", .{bytes[0..len]});
    defer a.free(scratch);
    var server = try (try std.Io.net.IpAddress.parse("127.0.0.1", 0)).listen(io, .{});
    defer server.deinit(io);
    const port = try std.fmt.allocPrint(a, "{d}", .{server.socket.address.getPort()});
    defer a.free(port);
    const control = try std.process.run(a, io, .{ .argv = &.{ options.network_fixture, port }, .stdout_limit = .limited(4096), .stderr_limit = .limited(4096), .timeout = .{ .duration = .{ .clock = .awake, .raw = .fromSeconds(2) } } });
    defer a.free(control.stdout);
    defer a.free(control.stderr);
    try std.testing.expect(control.term.success());
    try std.testing.expectEqualStrings("connected", control.stdout);
    var ctx = try core.context.Context.open(":memory:", .{});
    defer ctx.close();
    var exec = try core.execution.Execution.open(&ctx, a, io, .{ .workspace = workspace, .scratch = scratch, .read_only = &.{std.fs.path.dirname(options.network_fixture).?}, .timeout_ms = 2000 });
    defer exec.close();
    const result = try exec.run(a, .{ .generation = try ctx.generation(), .argv = &.{ options.network_fixture, port }, .timeout_ms = 2000 }, null, null, null);
    try std.testing.expectEqualStrings("exit", result.term_kind);
    try std.testing.expectEqual(@as(i64, 0), result.term_value);
    const stdout = try exec.output(a, result.id, false);
    defer a.free(stdout);
    try std.testing.expect(std.mem.startsWith(u8, stdout, "denied:"));
    try std.testing.expect(std.mem.indexOf(u8, stdout, "PERM") != null or std.mem.indexOf(u8, stdout, "ACCES") != null or std.mem.indexOf(u8, stdout, "NETUNREACH") != null or std.mem.indexOf(u8, stdout, "CONNREFUSED") != null);
}

test "isolated Zig compilation detects a real failing test and passes after a versioned source repair" {
    const a = std.testing.allocator;
    const io = std.testing.io;
    if (@import("builtin").os.tag == .linux) std.Io.Dir.cwd().access(io, "/usr/bin/bwrap", .{ .execute = true }) catch return error.SkipZigTest;
    var tmp = std.testing.tmpDir(.{});
    defer tmp.cleanup();
    try tmp.dir.createDir(io, "workspace", .default_dir);
    try tmp.dir.createDir(io, "scratch", .default_dir);
    var buffer: [std.Io.Dir.max_path_bytes]u8 = undefined;
    const len = try tmp.dir.realPath(io, &buffer);
    const workspace = try std.fmt.allocPrint(a, "{s}/workspace", .{buffer[0..len]});
    defer a.free(workspace);
    const scratch = try std.fmt.allocPrint(a, "{s}/scratch", .{buffer[0..len]});
    defer a.free(scratch);
    const compiler = try std.Io.Dir.cwd().realPathFileAlloc(io, options.zig_executable, a);
    defer a.free(compiler);
    const source = "const std = @import(\"std\");\npub fn answer() u8 { return 41; }\ntest \"answer\" { try std.testing.expectEqual(@as(u8,42), answer()); }\n";
    try tmp.dir.writeFile(io, .{ .sub_path = "workspace/answer.zig", .data = source });
    const local_cache = try std.fmt.allocPrint(a, "{s}/local-cache", .{scratch});
    defer a.free(local_cache);
    const global_cache = try std.fmt.allocPrint(a, "{s}/global-cache", .{scratch});
    defer a.free(global_cache);
    var ctx = try core.context.Context.open(":memory:", .{});
    defer ctx.close();
    var repo = try core.repository.Repository.open(&ctx, a, io, workspace, &.{.{ .path = "answer.zig", .write = true }});
    defer repo.close();
    var before = try repo.read(a, "answer.zig", null);
    defer before.deinit(a);
    var exec = try core.execution.Execution.open(&ctx, a, io, .{ .workspace = workspace, .scratch = scratch, .read_only = &.{std.fs.path.dirname(compiler).?}, .timeout_ms = 120000, .output_bytes = 65536 });
    defer exec.close();
    const command = &[_][]const u8{ compiler, "test", "answer.zig", "--cache-dir", local_cache, "--global-cache-dir", global_cache };
    const failed = try exec.run(a, .{ .generation = try ctx.generation(), .argv = command, .timeout_ms = 120000 }, null, null, null);
    const diagnostic = try exec.output(a, failed.id, true);
    defer a.free(diagnostic);
    if (!std.mem.eql(u8, failed.term_kind, "exit") or std.mem.indexOf(u8, diagnostic, "expected 42, found 41") == null) std.debug.print("isolated compiler {s}:{d}: {s}\n", .{ failed.term_kind, failed.term_value, diagnostic });
    try std.testing.expectEqualStrings("exit", failed.term_kind);
    try std.testing.expect(failed.term_value != 0 and !failed.incomplete);
    try std.testing.expect(std.mem.indexOf(u8, diagnostic, "expected 42, found 41") != null);
    const start = std.mem.indexOf(u8, source, "41").?;
    _ = try repo.apply(a, .{ .scope = repo.scope, .generation = try ctx.generation(), .edits = &.{.{ .path = "answer.zig", .ref = before.ref, .replacements = &.{.{ .start = start, .end = start + 2, .text = "42" }} }} }, null);
    const verified = try exec.run(a, .{ .generation = try ctx.generation(), .argv = command, .timeout_ms = 120000 }, null, null, null);
    const evidence = try exec.output(a, verified.id, true);
    defer a.free(evidence);
    if (verified.term_value != 0) std.debug.print("isolated repaired compiler {s}:{d}: {s}\n", .{ verified.term_kind, verified.term_value, evidence });
    try std.testing.expectEqualStrings("exit", verified.term_kind);
    try std.testing.expectEqual(@as(i64, 0), verified.term_value);
    try std.testing.expect(std.mem.indexOf(u8, evidence, "1 tests passed") != null);
}

test "SIGKILL at staged and swapped edit boundaries preserves source and forbids replay after reopen" {
    const a = std.testing.allocator;
    const io = std.testing.io;
    for ([_][]const u8{ "staged", "after_exchange" }, 0..) |point, index| {
        var tmp = std.testing.tmpDir(.{});
        defer tmp.cleanup();
        var buffer: [std.Io.Dir.max_path_bytes]u8 = undefined;
        const length = try tmp.dir.realPath(io, &buffer);
        const root = buffer[0..length];
        const path = try std.fmt.allocPrintSentinel(a, "{s}/journal.sqlite", .{root}, 0);
        defer a.free(path);
        try tmp.dir.writeFile(io, .{ .sub_path = "main.zig", .data = "old\n" });
        var child = try std.process.spawn(io, .{ .argv = &.{ options.crash_fixture, root, path, point }, .stdin = .ignore, .stdout = .ignore, .stderr = .inherit });
        defer child.kill(io);
        const term = try child.wait(io);
        try std.testing.expect(term == .signal and term.signal == .KILL);
        var ctx = try core.context.Context.open(path, .{});
        defer ctx.close();
        var repo = try core.repository.Repository.open(&ctx, a, io, root, &.{.{ .path = "main.zig", .write = true }});
        defer repo.close();
        try repo.recoverAfterOwnerExit();
        try std.testing.expectEqual(@as(i64, 1), try ctx.database.number("SELECT count(*) FROM edit_batches WHERE state='attention' AND diagnostic='OwnerExited';", &.{}));
        const target = try tmp.dir.readFileAlloc(io, "main.zig", a, .limited(4096));
        defer a.free(target);
        try std.testing.expectEqualStrings(if (index == 0) "old\n" else "new\n", target);
        var entry = try ctx.database.prepare("SELECT recovery_name FROM edit_entries WHERE batch_id=1;");
        defer entry.deinit();
        try std.testing.expect(try entry.step());
        const retained = try tmp.dir.readFileAlloc(io, entry.text(0), a, .limited(4096));
        defer a.free(retained);
        try std.testing.expectEqualStrings(if (index == 0) "new\n" else "old\n", retained);
        var current = try repo.read(a, "main.zig", null);
        defer current.deinit(a);
        try std.testing.expectError(error.EditNeedsReview, repo.apply(a, .{ .scope = repo.scope, .generation = try ctx.generation(), .edits = &.{.{ .path = "main.zig", .ref = current.ref, .replacements = &.{.{ .start = 0, .end = 3, .text = "next" }} }} }, null));
        try std.testing.expectEqual(@as(i64, 1), try ctx.database.number("SELECT count(*) FROM edit_batches;", &.{}));
        try std.testing.expectEqual(@as(i64, 0), try ctx.database.number("SELECT count(*) FROM pragma_foreign_key_check;", &.{}));
    }
